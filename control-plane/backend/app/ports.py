"""Runtime and engine contracts do not expose vendor response objects."""

from typing import Protocol


class WorkerRuntime(Protocol):
    def list(self) -> list[dict]: ...
    def create(self, worker, snapshot, token: str) -> str: ...
    def configure(self, worker, snapshot, token: str) -> str: ...
    def action(self, worker_id: str, action: str) -> None: ...
    def logs(self, runtime_id: str, limit: int) -> str: ...


class WorkflowEngine(Protocol):
    def workers(self) -> list[dict]: ...
    def runs(self, offset: int, limit: int) -> list[dict]: ...
    def run(self, external_id: str) -> dict: ...
    def logs(self, external_id: str, limit: int) -> list[dict]: ...
